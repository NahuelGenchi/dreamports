const SKIN = ['#ffe3cc', '#ffdcbc', '#f7d0b0', '#f3c39c'];
const HAIR = ['#2b1e1a', '#5a3a22', '#8a5a2a', '#e8b850', '#c4482a', '#1c1c2c', '#e8e4dc', '#3a2a4a'];
const SHIRT = ['#e84a4a', '#4a8ae8', '#f2c23e', '#46c27a', '#a25ad8', '#ff8a3a', '#f272aa', '#f4f4f4', '#3ac2ca', '#2f5fb8'];
const PANTS = ['#36467a', '#2a2a3a', '#6a4a2a', '#4a6a8a', '#7a3a3a', '#3a5a3a'];

export function personColours(R, T, over = {}) {
  const tone = (c) => T.tone(c, 0.9);
  return {
    h: tone(over.hair ?? R.pick(HAIR)),
    s: tone(over.skin ?? R.pick(SKIN)),
    e: tone('#1a1420'),
    c: tone(over.shirt ?? R.pick(SHIRT)),
    l: tone(over.pants ?? R.pick(PANTS)),
    f: tone('#3a2620'),
  };
}

// A person standing on `base` at x. `pose` is a sprite name; the outline follows the time of day.
export function person(p, T, R, x, base, { pose = 'person', flip = false, colours, outline } = {}) {
  const art = ART[pose];
  const pal = colours ?? personColours(R, T);
  p.sprite(x, base - art.length, art, pal, { flip, outline: outline ?? T.tone('#24182a', 0.4) });
  return pal;
}

// any sprite with its own palette, outlined in a deep shade of its first colour unless told otherwise
export function draw(p, T, name, x, y, pal, { flip = false, outline = true, k = 1 } = {}) {
  const toned = Object.fromEntries(Object.entries(pal).map(([key, c]) => [key, T.tone(c, k)]));
  const first = Object.values(pal)[0];
  const line = outline === true ? T.tone(deep(first, 0.55), k * 0.5) : outline ? T.tone(outline, k * 0.5) : null;
  p.sprite(x, y, ART[name], toned, { flip, outline: line });
}

export const size = (name) => ({ w: Math.max(...ART[name].map((r) => r.length)), h: ART[name].length });

export { hex, mix };
